"""`make setup`: create or complete the root `.env` and the domain credential files (doc 16).

Standard library only, so it runs in a bare `python:3.12-slim` container before any
image is built. It copies `.env.example` when there is no `.env`, then fills every
generated key that is missing or empty. It creates each missing
`domains/<id>/credentials/<set>.env` from its `.env.example`. It never overwrites a value
or file that is already there, and it prints only key and file names: what it filled, and
what the operator still has to fill in by hand.
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import sys
import tempfile
import uuid
from collections.abc import Callable, Sequence
from pathlib import Path


def _token() -> str:
    return secrets.token_urlsafe(32)


def _fernet_key() -> str:
    """A key `cryptography.fernet.Fernet` accepts: 32 random bytes, urlsafe-base64 (stdlib only,
    this script never imports `cryptography`)."""
    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()


GENERATORS: dict[str, Callable[[], str]] = {
    "POSTGRES_PASSWORD": _token,
    "SESSION_SECRET": _token,
    "EXECD_TOKEN": _token,
    "TELEGRAM_WEBHOOK_SECRET": _token,
    "LANGFUSE_PUBLIC_KEY": lambda: f"pk-lf-{uuid.uuid4()}",
    "LANGFUSE_SECRET_KEY": lambda: f"sk-lf-{uuid.uuid4()}",
    "LANGFUSE_NEXTAUTH_SECRET": _token,
    "LANGFUSE_SALT": _token,
    "LANGFUSE_ENCRYPTION_KEY": lambda: secrets.token_hex(32),
    "CREDENTIAL_ENCRYPTION_KEY": _fernet_key,
    "CLICKHOUSE_PASSWORD": _token,
    "REDIS_AUTH": _token,
    "MINIO_ROOT_PASSWORD": _token,
}
GENERATED_KEYS = tuple(GENERATORS)

# Keys the operator writes by hand (left blank in `.env.example`).
OPERATOR_KEYS = ("OPENROUTER_API_KEY", "ADMIN_USERNAME", "ADMIN_PASSWORD")
OPTIONAL_OPERATOR_KEYS = (
    "DEMO_PASSWORD",
    "TELEGRAM_BOT_TOKEN",
    "TELEGRAM_BOT_USERNAME",
)

# Settings that compose sets for the containers; they are not part of `.env.example`.
INTERNAL_KEYS = (
    "DATABASE_URL",
    "EXECD_URL",
    "LANGFUSE_BASE_URL",
    "DOMAINS_DIR",
    "PLATFORM_DIR",
    "FOLDERS_DIR",
    "ATTACHMENTS_DIR",
    "REPORTS_DIR",
    "CACHE_DIR",
    "SKILLS_CODELOAD_URL",
    "GITHUB_API_URL",
    "MODEL_SCENARIO",
    "INTERNAL_URL",
    "INTERNAL_PORT",
    "RUNNER_POLL_S",
    "RUNNER_DEBOUNCE_S",
)


def _key_of(line: str) -> str | None:
    stripped = line.strip()
    if not stripped or stripped.startswith("#") or "=" not in stripped:
        return None
    return stripped.split("=", 1)[0].removeprefix("export ").strip()


def _is_empty(line: str) -> bool:
    return line.split("=", 1)[1].strip().strip("'\"").strip() == ""


def _write_private(path: Path, text: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def init_env(env_path: Path, example_path: Path) -> list[str]:
    """Create/complete `env_path`; return the names of the keys that were filled."""
    if env_path.exists():
        text = env_path.read_text(encoding="utf-8")
    else:
        text = example_path.read_text(encoding="utf-8")

    lines = text.splitlines()
    seen: set[str] = set()
    filled: list[str] = []
    for i, line in enumerate(lines):
        key = _key_of(line)
        if key is None:
            continue
        seen.add(key)
        if key in GENERATORS and _is_empty(line):
            lines[i] = f"{key}={GENERATORS[key]()}"
            filled.append(key)

    missing = [k for k in GENERATED_KEYS if k not in seen]
    if missing:
        lines.append("")
        lines.append("# Generated by make setup")
        for key in missing:
            lines.append(f"{key}={GENERATORS[key]()}")
            filled.append(key)

    new_text = "\n".join(lines) + "\n"
    if not env_path.exists() or new_text != text:
        _write_private(env_path, new_text)
    else:
        os.chmod(env_path, 0o600)
    return filled


def copy_credential_templates(domains_dir: Path) -> list[Path]:
    """Create each missing `credentials/<set>.env` from its template; return the new files."""
    created = []
    for template in sorted(domains_dir.glob("*/credentials/*.env.example")):
        target = template.with_name(template.name.removesuffix(".example"))
        if not target.exists():
            _write_private(target, template.read_text(encoding="utf-8"))
            created.append(target)
    return created


def empty_keys(path: Path) -> list[str]:
    """Keys of `path` whose value is empty, in file order."""
    keys = []
    for line in path.read_text(encoding="utf-8").splitlines():
        key = _key_of(line)
        if key is not None and _is_empty(line):
            keys.append(key)
    return keys


def _unset(env_path: Path, keys: Sequence[str]) -> list[str]:
    present = {_key_of(line) for line in env_path.read_text(encoding="utf-8").splitlines()}
    empty = set(empty_keys(env_path))
    return [k for k in keys if k in empty or k not in present]


def to_fill_lines(env_path: Path, domains_dir: Path) -> list[str]:
    """What the operator still has to fill in, by file and key name only."""
    required = []
    operator = _unset(env_path, OPERATOR_KEYS)
    if operator:
        required.append(f"  {env_path}: {', '.join(operator)}")
    for cred in sorted(domains_dir.glob("*/credentials/*.env")):
        keys = empty_keys(cred)
        if keys:
            required.append(f"  {cred}: {', '.join(keys)}")
    optional = _unset(env_path, OPTIONAL_OPERATOR_KEYS)

    out = []
    if required:
        out.append("still to fill in:")
        out.extend(required)
    if optional:
        out.append(f"optional: {env_path}: {', '.join(optional)}")
    if required:
        out.append("next: fill these in, then run `make check` (see GUIDE.md)")
    else:
        out.append("nothing to fill; run `make up`")
    return out


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--env", default=".env", type=Path)
    parser.add_argument("--example", default=".env.example", type=Path)
    parser.add_argument("--domains", default="domains", type=Path)
    args = parser.parse_args(argv)

    created = not args.env.exists()
    filled = init_env(args.env, args.example)
    if created:
        print(f"created {args.env} from {args.example}")
    if filled:
        print("filled generated keys: " + ", ".join(filled))
    else:
        print("no generated keys to fill")
    for path in copy_credential_templates(args.domains):
        print(f"created {path}")
    print()
    print("\n".join(to_fill_lines(args.env, args.domains)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
