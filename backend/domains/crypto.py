"""Encrypting credential values at rest (doc 12 "Domains"): `domain_credential_values.ciphertext`
is a Fernet token, decrypted only by the backend process (never by `execd`, never returned over
the API). The key lives in `CREDENTIAL_ENCRYPTION_KEY` (`.env`), generated by `backend.init_env`,
never stored in Postgres.
"""

from __future__ import annotations

from functools import lru_cache

from cryptography.fernet import Fernet, InvalidToken

from backend.settings import Settings


class CredentialCryptoError(Exception):
    pass


@lru_cache(maxsize=1)
def _fernet(key: str) -> Fernet:
    return Fernet(key.encode())


def encrypt(settings: Settings, plaintext: str) -> bytes:
    key = settings.CREDENTIAL_ENCRYPTION_KEY.get_secret_value()
    if not key:
        raise CredentialCryptoError("CREDENTIAL_ENCRYPTION_KEY is not set")
    return _fernet(key).encrypt(plaintext.encode())


def decrypt(settings: Settings, ciphertext: bytes) -> str:
    key = settings.CREDENTIAL_ENCRYPTION_KEY.get_secret_value()
    if not key:
        raise CredentialCryptoError("CREDENTIAL_ENCRYPTION_KEY is not set")
    try:
        return _fernet(key).decrypt(bytes(ciphertext)).decode()
    except InvalidToken as e:
        raise CredentialCryptoError("credential value does not decrypt with this key") from e
